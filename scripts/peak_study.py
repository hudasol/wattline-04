"""Descriptive peak event study from the saved locked test predictions.

Reads results/final/test_predictions.csv and results/final/metrics.json, changes no
decision and fits nothing. It only describes what the served HIGH_DEMAND flag caught and
missed, so a reader can judge how much to trust it. Output: results/final/peak_study.md.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PRED = ROOT / "results" / "final" / "test_predictions.csv"
METRICS = ROOT / "results" / "final" / "metrics.json"
OUT = ROOT / "results" / "final" / "peak_study.md"

WINDOWS = [
    ("night 23:00 to 05:59", lambda h: (h >= 23) | (h <= 5)),
    ("morning 06:00 to 09:59", lambda h: h.between(6, 9)),
    ("midday 10:00 to 16:59", lambda h: h.between(10, 16)),
    ("evening 17:00 to 22:59", lambda h: h.between(17, 22)),
]


def load() -> tuple[pd.DataFrame, float]:
    threshold = json.loads(METRICS.read_text())["advisory"]["rule"]["high_kwh"]
    d = pd.read_csv(PRED)
    d = d[d["scored"]].copy()
    d["actual_high"] = d["actual_kwh"] >= threshold
    d["flag"] = d["advisory"] == "HIGH_DEMAND"
    d["hour"] = pd.to_datetime(d["target_local"].str[:19]).dt.hour
    return d, threshold


def counts(x: pd.DataFrame) -> tuple[int, int, int, float, float]:
    tp = int((x["flag"] & x["actual_high"]).sum())
    n_high, n_flag = int(x["actual_high"].sum()), int(x["flag"].sum())
    precision = tp / n_flag if n_flag else float("nan")
    recall = tp / n_high if n_high else float("nan")
    return n_high, n_flag, tp, precision, recall


def table(rows: list[tuple[str, pd.DataFrame]]) -> list[str]:
    lines = [
        "| slice | hours | real high hours | flagged | caught | precision | recall |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, x in rows:
        n_high, n_flag, tp, p, r = counts(x)
        lines.append(f"| {name} | {len(x)} | {n_high} | {n_flag} | {tp} | {p:.2f} | {r:.2f} |")
    return lines


def main() -> None:
    d, thr = load()
    rows = [(n, d[f(d["hour"])]) for n, f in WINDOWS] + [("all scored hours", d)]
    day = pd.to_datetime(d["target_local"].str[:10]).dt.dayofweek
    rows_day = [("weekdays", d[day < 5]), ("weekend days", d[day >= 5])]
    big = d["actual_kwh"] > 3.0
    mid = d["actual_high"] & ~big
    false_alarms = d[d["flag"] & ~d["actual_high"]]
    per_day = d.groupby(d["target_local"].str[:10]).agg(
        high=("actual_high", "max"), flag=("flag", "max")
    )
    out = [
        "# Peak event study (descriptive, locked test)",
        "",
        f"Generated by `scripts/peak_study.py` from `results/final/test_predictions.csv`. "
        f"HIGH threshold {thr:.3f} kWh. Nothing here was tuned or used to change a decision.",
        "",
        "## What the served flag catches and misses, by time of day",
        "",
        *table(rows),
        "",
        "## By day type",
        "",
        *table(rows_day),
        "",
        "## By size of the real peak",
        "",
        "| real hour | hours | caught by the flag |",
        "|---|---|---|",
        f"| between {thr:.2f} and 3.00 kWh | {int(mid.sum())} | {int((mid & d['flag']).sum())} |",
        f"| above 3.00 kWh | {int(big.sum())} | {int((big & d['flag']).sum())} |",
        "",
        "## False alarms",
        "",
        f"{len(false_alarms)} flagged hours were not high. Median actual load in those hours "
        f"was {false_alarms['actual_kwh'].median():.2f} kWh and "
        f"{int((false_alarms['actual_kwh'] >= 1.8).sum())} of them reached 1.80 kWh or more "
        f"(77 percent of the threshold), so many were elevated hours that stayed just under it.",
        "",
        "## Day level view",
        "",
        f"{int(per_day['flag'].sum())} of {len(per_day)} test days contained at least one "
        f"flagged hour and {int(per_day['high'].sum())} contained a real high hour. A day level "
        "flag therefore carries almost no information; only the hour and window do.",
    ]
    OUT.write_text("\n".join(out).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    print(f"written: {OUT}")


if __name__ == "__main__":
    main()
